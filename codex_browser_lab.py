#!/usr/bin/env python3
"""Enable Codex Browser Use local-testing mode (macOS + Windows).

Codex Browser Use calls https://chatgpt.com/backend-api/aura/site_status
before every navigation. That cloud check blocks legitimate sites
(Taobao, 1688, Pixiv, …) even when the user allowlisted them.

The bundled plugin already understands:

    BROWSER_USE_SECURITY_MODE=disabled-for-local-testing

which skips check-url-site-status. This tool turns that flag on locally
and, optionally, expands origin allowlists. ChatGPT/Codex updates rewrite
~/.codex/config.toml; `install --persist` re-applies the patch
(LaunchAgent on macOS; HKCU Run watcher + Scheduled Task on Windows).

macOS injects the flag by pointing [mcp_servers.node_repl] `command` at a
bash wrapper that exports the variable and `exec`s the signed node_repl.

Windows leaves `command` on the official node_repl.exe and writes the flag
into [mcp_servers.node_repl.env]. Codex regenerates that block on every
launch and synthesises node_repl's environment, so the patch is re-applied
after each start.
"""
