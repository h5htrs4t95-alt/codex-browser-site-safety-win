def backup(path: Path) -> None:
    """Copy `path` aside before it is rewritten.

    The backup name is derived from the path relative to CODEX_HOME, so
    config.toml and browser/config.toml never overwrite each other.
    """
    if not path.exists():
        return
    dest_dir = wrappers_dir() / "backups"
    dest_dir.mkdir(parents=True, exist_ok=True)
    try:
        rel = path.resolve().relative_to(codex_home().resolve())
        stem = "_".join(rel.parts)
    except (ValueError, OSError):
        stem = path.name
    stamp = datetime.now().strftime("%Y%m%d%H%M%S")
    dest = dest_dir / f"{stem}.{stamp}"
    n = 2
    while dest.exists():
        dest = dest_dir / f"{stem}.{stamp}-{n}"
        n += 1
    shutil.copy2(path, dest)


def ensure_wrapper(*, dry: bool, quiet: bool) -> Path:
    path = wrapper_path()
    if dry:
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or read_text(path) != WRAPPER_BODY:
        write_text(path, WRAPPER_BODY)
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    log(f"wrapper: {path}", quiet=quiet)
    return path


def patch_config(domains: list[str], *, dry: bool, quiet: bool) -> bool:
    path = config_toml()
    if not path.exists():
        raise SystemExit(f"missing {path}; is Codex/ChatGPT installed?")
    text = read_text(path)
    if table_span(text, "mcp_servers.node_repl") is None:
        raise SystemExit(f"no [mcp_servers.node_repl] in {path}")
    original = text
    if IS_WIN:
        # Codex hands this env table straight to node_repl.exe; no wrapper.
        text = ensure_table(text, "mcp_servers.node_repl.env")
        text = set_key(text, "mcp_servers.node_repl.env", "BROWSER_USE_SECURITY_MODE", MODE)
    else:
        text = set_key(text, "mcp_servers.node_repl", "command", str(wrapper_path()))
        text = ensure_table(text, "mcp_servers.node_repl.env")
        text = set_key(text, "mcp_servers.node_repl.env", "BROWSER_USE_SECURITY_MODE", MODE)
    if domains:
        text = ensure_origin_tables(text, domains)
    if text == original:
        log(f"unchanged: {path}", quiet=quiet)
        return False
    if dry:
        log(f"would patch: {path}", quiet=quiet)
        return True
    backup(path)
    write_text(path, text)
    log(f"patched: {path}", quiet=quiet, important=True)
    return True


def patch_browser_config(domains: list[str], *, dry: bool, quiet: bool) -> bool:
    if not domains:
        return False
    path = browser_toml()
    urls: list[str] = []
    for domain in domains:
        urls.append(f"https://{domain}")
        urls.append(f"https://*.{domain}")
    if not path.exists():
        body = (
            'approval_mode = "never_ask"\n'
            'history_approval_mode = "never_ask"\n'
            'download_approval_mode = "never_ask"\n'
            'upload_approval_mode = "never_ask"\n'
            "full_cdp_access_enabled = true\n\n"
        )
        for table in ("origins", "downloads", "uploads", "full_cdp"):
            inner = ",\n".join(f'  "{u}"' for u in urls)
            body += f"[{table}]\nallowed = [\n{inner},\n]\ndenied = []\n\n"
        if dry:
            log(f"would create: {path}", quiet=quiet)
            return True
        path.parent.mkdir(parents=True, exist_ok=True)
        write_text(path, body)
        log(f"created: {path}", quiet=quiet)
        return True
    text = read_text(path)
    original = text
    for table in ("origins", "downloads", "uploads", "full_cdp"):
        text = merge_allowed_array(text, table, urls)
    if text == original:
        log(f"unchanged: {path}", quiet=quiet)
        return False
    if dry:
        log(f"would patch: {path}", quiet=quiet)
        return True
    backup(path)
    write_text(path, text)
    log(f"patched: {path}", quiet=quiet, important=True)
    return True


def patch_cua_mcp(*, dry: bool, quiet: bool) -> int:
    root = plugin_cache() / "unified-computer-use"
    if not root.exists():
        log("no unified-computer-use plugin cache (skip)", quiet=quiet)
        return 0
    changed = 0
    wrap = str(wrapper_path())
    for mcp in sorted(root.glob("*/.mcp.json")):
        data = json.loads(read_text(mcp))
        env = data.get("mcpServers", {}).get("cua_repl", {}).get("env")
        if not isinstance(env, dict):
            continue
        before = dict(env)
        env["BROWSER_USE_SECURITY_MODE"] = MODE
        if not IS_WIN:
            env["CUA_REPL_NODE_REPL_PATH"] = wrap
        if env == before:
            continue
        if dry:
            log(f"would patch: {mcp}", quiet=quiet)
            changed += 1
            continue
        backup(mcp)
        write_text(mcp, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
        log(f"patched: {mcp}", quiet=quiet, important=True)
        changed += 1
    return changed


def patch_navigation_blocked(*, dry: bool, quiet: bool) -> int:
    """Ignore Chrome Page.navigationBlocked and default to local-testing mode.

    site_status is skipped by the env flag, but in-page actions can still
    throw browser_navigation_blocked ("not permitted on <url>") when CDP
    emits Page.navigationBlocked.  Windows also spawns some node_repl
    processes through plugin helpers that never inherit the env flag, so the
    security-mode resolver is changed to treat "unset" as local-testing.
    """
    changed = 0
    for path in browser_service_files():
        text = path.read_text(errors="replace")
        new = text
        touched = False
        if NAV_BLOCK_GUARD not in new:
            sub, n = NAV_BLOCK_RE.subn(r"\1" + NAV_BLOCK_GUARD + r"\2", new, count=1)
            if n:
                new = sub
                touched = True
            else:
                log(f"no Page.navigationBlocked hook in {path} (skip)", quiet=quiet)
        sub, n = FT_DEFAULT_RE.subn(r'\1"' + FT_DEFAULT_VALUE + '"}', new, count=1)
        if n:
            new = sub
            touched = True
        else:
            log(f"no security-mode default hook in {path} (skip)", quiet=quiet)
        if not touched:
            continue
        if dry:
            log(f"would patch browser service: {path}", quiet=quiet)
            changed += 1
            continue
        backup(path)
        write_text(path, new)
        log(f"patched browser service: {path}", quiet=quiet, important=True)
        changed += 1
    return changed


def _browser_service_fingerprint() -> tuple[tuple[str, float, int], ...]:
    rows: list[tuple[str, float, int]] = []
    for path in browser_service_files():
        try:
            st = path.stat()
        except OSError:
            continue
        rows.append((str(path), st.st_mtime, st.st_size))
    return tuple(rows)


