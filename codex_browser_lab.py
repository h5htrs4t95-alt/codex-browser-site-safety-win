def _config_node_repl_command() -> Path | None:
    cfg = config_toml()
    if not cfg.exists():
        return None
    try:
        text = read_text(cfg)
    except (OSError, UnicodeDecodeError):
        return None
    span = table_span(text, "mcp_servers.node_repl")
    if span is None:
        return None
    m = re.search(
        r"""(?m)^\s*command\s*=\s*(['"])(.*?)\1\s*$""", text[span[0] : span[1]]
    )
    if not m:
        return None
    p = Path(m.group(2))
    return p if p.is_file() else None


def official_node_repl() -> Path | None:
    if IS_WIN:
        cfg_cmd = _config_node_repl_command()
        if cfg_cmd is not None and cfg_cmd.name.lower() == "node_repl.exe":
            return cfg_cmd
        root = windows_cua_root()
        if root.is_dir():
            try:
                cands = sorted(
                    root.glob("*/bin/node_repl.exe"),
                    key=lambda p: p.stat().st_mtime,
                    reverse=True,
                )
            except OSError:
                cands = []
            for c in cands:
                if c.is_file():
                    return c
        return None
    for p in (
        Path("/Applications/ChatGPT.app/Contents/Resources/cua_node/bin/node_repl"),
        Path("/Applications/Codex.app/Contents/Resources/cua_node/bin/node_repl"),
    ):
        if p.is_file():
            return p
    return None


def runtime_browser_service_files() -> list[Path]:
    """Copies shipped inside the cua_node runtime, loaded by plugin helpers.

    Codex desktop on Windows can load the browser service from these paths
    instead of the plugin cache, so they need the same patches.
    """
    files: list[Path] = []
    root = windows_cua_root()
    if root.exists():
        rels = (
            Path("@oai") / "browser-desktop" / "scripts" / "browser-service.mjs",
            Path("@oai") / "cua" / "dist" / "lib" / "js" / "oai_js_browser"
            / "dist" / "skill" / "scripts" / "browser-service.mjs",
        )
        for base in sorted(root.glob("*/bin/node_modules")):
            for rel in rels:
                path = base / rel
                if path.is_file():
                    files.append(path)
    return files


def browser_service_files() -> list[Path]:
    files: list[Path] = []
    for name in ("chrome", "browser"):
        root = plugin_cache() / name
        if root.exists():
            files.extend(sorted(root.glob("*/scripts/browser-service.mjs")))
    files.extend(runtime_browser_service_files())
    return files


def security_mode_support() -> tuple[bool | None, str]:
    """Does the installed browser-service.mjs still implement the flag?"""
    candidates = browser_service_files()
    candidates.sort(
        key=lambda p: p.stat().st_mtime if p.exists() else 0,
        reverse=True,
    )
    for path in candidates:
        if not path.is_file():
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        version = path.parent.parent.name
        supported = (
            "disabled-for-local-testing" in text and "check-url-site-status" in text
        )
        return supported, version
    return None, "browser-service.mjs not found"


