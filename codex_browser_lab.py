WRAPPER_BODY = r"""#!/usr/bin/env bash
# Generated by codex-browser-lab. exec keeps the signed node_repl image.
set -euo pipefail
export BROWSER_USE_SECURITY_MODE="${BROWSER_USE_SECURITY_MODE:-disabled-for-local-testing}"

candidates=(
  "/Applications/ChatGPT.app/Contents/Resources/cua_node/bin/node_repl"
  "/Applications/Codex.app/Contents/Resources/cua_node/bin/node_repl"
)
bin=""
for c in "${candidates[@]}"; do
  if [[ -x "$c" ]]; then
    bin="$c"
    break
  fi
done
if [[ -z "$bin" ]]; then
  echo "codex-browser-lab: node_repl not found in ChatGPT.app or Codex.app" >&2
  exit 1
fi
exec "$bin" "$@"
"""

NAV_BLOCK_RE = re.compile(
    r"(function \w+\(\w+\)\{if\(\w+==null\|\|!\w+\(\w+\)\)return;)"
    r"(let \w+=\w+\(\w+\.params\.url\)\?\?\"this page\";"
    r"throw new \w+\(\"browser_navigation_blocked\","
    r"`Browser Use is not permitted on \$\{\w+\}\.`\)\})"
)
NAV_BLOCK_GUARD = (
    'if((typeof process<"u"?process.env.BROWSER_USE_SECURITY_MODE:"")'
    '==="disabled-for-local-testing")return;'
)
