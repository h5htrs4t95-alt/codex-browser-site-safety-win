def _python_for_task() -> str:
    exe = Path(sys.executable)
    if IS_WIN:
        pyw = exe.with_name("pythonw.exe")
        if pyw.exists():
            return str(pyw)
    return str(exe)


def write_repair_cmd(*, quiet: bool) -> Path:
    """Tiny .cmd shim so the scheduled task never needs nested quoting."""
    cmd = win_repair_cmd()
    cmd.parent.mkdir(parents=True, exist_ok=True)
    body = (
        "@echo off\r\n"
        "rem Generated by codex-browser-lab; re-applies the security-mode patch.\r\n"
        f'"{_python_for_task()}" "{installed_script()}" repair >> "{log_path()}" 2>&1\r\n'
    )
    if not cmd.exists() or read_text(cmd) != body:
        write_text(cmd, body)
    log(f"repair shim: {cmd}", quiet=quiet)
    return cmd


def _schtasks(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["schtasks", *args], capture_output=True, text=True, errors="replace"
    )


def persist_windows(*, quiet: bool, interval: int = DEFAULT_WIN_INTERVAL_MIN) -> None:
    if interval < 1:
        interval = 1
    install_self(quiet=quiet)
    shim = write_repair_cmd(quiet=quiet)
    set_win_run(WIN_WATCH, win_watch_command())
    log(f"autostart: HKCU\\...\\Run\\{WIN_WATCH}", quiet=quiet)
    try:
        start_watcher(quiet=quiet)
    except OSError as exc:
        log(f"warn: could not start the watcher now - {exc}", quiet=quiet, important=True)
    tr = f'"{shim}"'
    r = _schtasks(
        "/Create", "/TN", WIN_TASK, "/TR", tr,
        "/SC", "MINUTE", "/MO", str(interval), "/F",
    )
    if r.returncode == 0:
        log(f"persist: scheduled task {WIN_TASK}", quiet=quiet)
    else:
        log(
            f"warn: scheduled task not registered - {(r.stderr or r.stdout).strip()}",
            quiet=quiet,
            important=True,
        )


def unpersist_windows(*, quiet: bool) -> None:
    stop_watcher(quiet=quiet)
    if delete_win_run(WIN_WATCH):
        log(f"removed autostart: {WIN_WATCH}", quiet=quiet)
    removed = False
    for name in (WIN_TASK, WIN_TASK_LOGON):
        r = _schtasks("/Delete", "/TN", name, "/F")
        if r.returncode == 0:
            log(f"removed scheduled task: {name}", quiet=quiet)
            removed = True
    if not removed:
        log("no scheduled task installed", quiet=quiet)
    shim = win_repair_cmd()
    if shim.exists():
        shim.unlink()
        log(f"removed repair shim: {shim}", quiet=quiet)


def persist(*, quiet: bool, interval: int = DEFAULT_WIN_INTERVAL_MIN) -> None:
    if IS_MAC:
        persist_macos(quiet=quiet)
    elif IS_WIN:
        persist_windows(quiet=quiet, interval=interval)
    else:
        raise SystemExit("--persist is supported on macOS and Windows only")


def unpersist(*, quiet: bool) -> None:
    if IS_MAC:
        unpersist_macos(quiet=quiet)
    elif IS_WIN:
        unpersist_windows(quiet=quiet)


def _task_state(name: str) -> str:
    r = _schtasks("/Query", "/TN", name)
    if r.returncode == 0:
        return "installed"
    message = f"{r.stdout or ''} {r.stderr or ''}".lower()
    if "cannot find" in message or "找不到" in message:
        return "absent"
    return "unknown"


def persist_status() -> str:
    if IS_MAC:
        agent = launch_agent_path()
        return f"LaunchAgent {agent} exists={agent.exists()}"
    if IS_WIN:
        return f"{WIN_TASK}={_task_state(WIN_TASK)}"
    return "n/a"


